#!/usr/bin/env python3
"""Port a newer Samsung release's epdg_apns_conf.xml to this device's EpdgService.

Usage: port_epdg_apns_conf.py <stock> <newer> <EpdgService apktool dir> <output>

The file holds EpdgService's per-carrier ePDG data: <vowifi> (default Wi-Fi
Calling switches), <apn> (IKE/IPsec profile per APN) and <settings> (handover
thresholds, ePDG address, ...), keyed by mnoname (and connname/apnname for
<apn>).

- Entries: the newer file's only, in its order; where it lists an entry twice,
  the first one is used.
- Newer releases only write what differs from the defaults on the section tags
  (<iwlansettings ...> for <apn>, <epdgsettings ...> for <settings>); this
  EpdgService expects every attribute on every entry, so each entry is
  expanded with its section's defaults.
- Attributes: the ones this EpdgService reads (a string in its smali). Those
  the newer release no longer has at all are taken from the stock file's
  entry of the same carrier, else its default entry of that kind, else the
  value most of its entries have: EpdgService stores a missing one as NULL
  and parses some with Integer.parseInt().
"""

import os
import re
import sys

SECTIONS = {'vowifi': 'vowifisettings', 'apn': 'iwlansettings', 'settings': 'epdgsettings'}
ELEMENT = re.compile(r'((?:[ \t]*<!--[^\n]*-->\n)?)([ \t]*)<(apn|settings|vowifi)\b(.*?)/>\n?', re.S)
ATTR = re.compile(r'([\w:]+)\s*=\s*"([^"]*)"')


def attrs(text):
    return dict(ATTR.findall(text))


def key(tag, a):
    if tag == 'apn':
        return (tag, a.get('mnoname'), a.get('connname'), a.get('apnname'))
    return (tag, a.get('mnoname'))


def section_defaults(text, section):
    m = re.search(r'<%s\b([^>]*)>' % section, text)
    return attrs(m.group(1)) if m else {}


def smali_strings(apk_dir):
    strings = set()
    for d in os.listdir(apk_dir):
        if not d.startswith('smali'):
            continue
        for root, _, files in os.walk(os.path.join(apk_dir, d)):
            for f in files:
                with open(os.path.join(root, f), encoding='utf-8') as s:
                    strings.update(re.findall(r'"((?:[^"\\]|\\.)*)"', s.read()))
    return strings


def element(tag, a, comment=''):
    items = list(a.items())
    lines = ['        <%s %s="%s"' % (tag, items[0][0], items[0][1])]
    lines += ['            %s="%s"' % i for i in items[1:]]
    lines.append('        />')
    if comment:
        comment = '        ' + comment.lstrip(' \t')
    return comment + '\n'.join(lines) + '\n'


def main(stock_path, newer_path, apk_dir, output):
    stock = open(stock_path).read()
    newer = open(newer_path).read()
    strings = smali_strings(apk_dir)

    stock_default = {}
    stock_entries = {}
    stock_values = {tag: {} for tag in SECTIONS}
    for m in ELEMENT.finditer(stock):
        a = attrs(m.group(4))
        stock_entries.setdefault(key(m.group(3), a), a)
        if a.get('mnoname') == 'default':
            stock_default.setdefault(m.group(3), a)
        for x, v in a.items():
            counts = stock_values[m.group(3)].setdefault(x, {})
            counts[v] = counts.get(v, 0) + 1

    entries = {tag: [] for tag in SECTIONS}
    seen = set()
    filled = set()
    for tag, section in SECTIONS.items():
        defaults = section_defaults(newer, section)
        newer_attrs = set(defaults)
        for m in ELEMENT.finditer(newer):
            if m.group(3) == tag:
                newer_attrs.update(attrs(m.group(4)))
        # Read by this EpdgService, gone from the newer release.
        missing = sorted(x for x in stock_values[tag]
                         if x in strings and x not in newer_attrs)
        # Stock's default entry lacks some of them (e.g. tepdgqualitychecktimer,
        # which addEpdgSetting() takes to Integer.parseInt()); those take the
        # value most stock entries have.
        fallback = dict(stock_default[tag])
        for x in missing:
            if x not in fallback:
                fallback[x] = max(stock_values[tag][x].items(), key=lambda i: i[1])[0]
        filled.update('%s %s' % (tag, x) for x in missing)
        for m in ELEMENT.finditer(newer):
            if m.group(3) != tag:
                continue
            a = dict(defaults)
            a.update(attrs(m.group(4)))
            k = key(tag, a)
            if k in seen:
                continue
            seen.add(k)
            a = {x: v for x, v in a.items() if x in strings}
            old = stock_entries.get(k, {})
            for x in missing:
                a[x] = old.get(x, fallback[x])
            a = dict([('mnoname', a.pop('mnoname'))] + list(a.items()))
            entries[tag].append(element(tag, a, m.group(1)))

    decl, _, head = newer[:newer.index('<iwlanapns')].partition('\n')
    out = (decl + '\n<!-- Generated by port_epdg_apns_conf.py. -->\n' + head +
           '<iwlanapns>\n')
    for tag, section in SECTIONS.items():
        out += '    <%s>\n%s    </%s>\n' % (section, ''.join(entries[tag]), section)
    out += '</iwlanapns>\n'
    open(output, 'w').write(out)
    print('%d vowifi, %d apn, %d settings entries; from stock default: %s' % (
        len(entries['vowifi']), len(entries['apn']), len(entries['settings']),
        ', '.join(sorted(filled))))


if __name__ == '__main__':
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
